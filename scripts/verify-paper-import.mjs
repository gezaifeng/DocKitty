import { _electron as electron, expect } from '@playwright/test'
import { promises as fs } from 'node:fs'
import path from 'node:path'
import { createHash } from 'node:crypto'
const audit=path.resolve('docs/paper-import-audit')
const manifest=JSON.parse(await fs.readFile(path.join(audit,'import-manifest.json'),'utf8'))
const env={...process.env};delete env.ELECTRON_RUN_AS_NODE
const app=await electron.launch({executablePath:path.resolve('dist/gaomiao-0.3.3-windows-x64/稿喵.exe'),args:[path.resolve('dist/gaomiao-0.3.3-windows-x64/resources/app')],env})
try{
 const page=await app.firstWindow(),errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.emulateMedia({reducedMotion:'reduce'})
 await expect(page.getByRole('button',{name:'总览工作台',exact:true})).toBeVisible()
 const row=page.locator('.wg-document-card').filter({hasText:'溶液光谱重建论文 · 从初稿到投稿修改'})
 await expect(row).toHaveCount(1);await row.click()
 const detail=await page.evaluate(name=>window.wordgit.library.detail(name),manifest.docName)
 expect(detail.versions).toHaveLength(16);expect(detail.currentBranch).toBe('Measurement投稿');expect(detail.workspace.dirty).toBe(false)
 const latest=manifest.versions.at(-1)
 await expect(page.locator('.wg-selected-version h3')).toHaveText(latest.title)
 await expect(page.locator('.wg-inspector .prose section').first()).toBeVisible({timeout:30000})
 await page.screenshot({path:path.join(audit,'最新版预览.png')})
 await page.locator('.wg-history-rows button').filter({hasText:manifest.versions[0].title}).click()
 await expect(page.locator('.wg-selected-version h3')).toHaveText(manifest.versions[0].title)
 await expect(page.locator('.wg-inspector .prose')).toContainText('基于轻量残差',{timeout:30000})
 await page.screenshot({path:path.join(audit,'最早稿预览.png')})
 await page.getByRole('button',{name:'版本关系图',exact:true}).click()
 await expect(page.locator('.wg-graph-node')).toHaveCount(16)
 for(let i=0;i<5;i++)await page.getByLabel('缩小关系图').click()
 await page.screenshot({path:path.join(audit,'真实版本关系图.png')})
 await page.getByRole('button',{name:'分类看板',exact:true}).click()
 await expect(page.locator('.wg-version-card')).toHaveCount(16)
 await page.screenshot({path:path.join(audit,'真实分类看板.png')})
 await page.getByRole('button',{name:'版本统计',exact:true}).click()
 await expect(page.locator('.wg-stat-heading h1')).toBeVisible()
 const stats=[]
 for(const branch of ['Measurement投稿','中文早期稿','英文改稿','TIP投稿','SAA投稿']){
  const data=await page.evaluate(({name,branch})=>window.wordgit.stats.versions(name,branch),{name:manifest.docName,branch})
  expect(data.versions.length).toBeGreaterThan(0)
  expect(data.versions.at(-1).values.wordCount).toBeGreaterThan(0)
  stats.push({branch,versions:data.versions.length,latestTitle:data.versions.at(-1).title,latestValues:data.versions.at(-1).values,warnings:data.warnings})
  console.log('Statistics checked: '+branch+' / '+data.versions.length)
 }
 await page.screenshot({path:path.join(audit,'统计加载诊断.png')})
 console.log('Statistics UI: '+await page.locator('.wg-statistics').innerText())
 await page.getByRole('button',{name:'中英混合字数',exact:false}).click()
 await expect(page.locator('.wg-stat-heading h1')).toHaveText('中英混合字数')
 await page.screenshot({path:path.join(audit,'Measurement真实字数统计.png')})
 await page.getByLabel('统计分支').selectOption('中文早期稿')
 await expect(page.locator('.wg-stat-cards section').first().locator('strong')).toHaveText('9')
 await page.screenshot({path:path.join(audit,'中文早期稿真实统计.png')})
 await page.getByLabel('统计分支').selectOption('Measurement投稿')
 await page.getByRole('button',{name:'章节变化',exact:true}).click()
 await expect(page.locator('.wg-stat-heading h1')).toHaveText('章节变化')
 await page.screenshot({path:path.join(audit,'最新稿章节变化.png')})
 expect(errors).toEqual([])
 expect((await page.evaluate(name=>window.wordgit.library.detail(name),manifest.docName)).currentBranch).toBe('Measurement投稿')
 const working=await fs.readFile(path.join(manifest.targetRoot,'workspace',manifest.docName))
 expect(createHash('sha256').update(working).digest('hex')).toBe(latest.sha256)
 await fs.writeFile(path.join(audit,'runtime-verification.json'),JSON.stringify({passed:true,versions:16,stats,errors,workspaceUnchanged:true},null,2))
 console.log('Real manuscript verified: 16 versions, original/latest preview, graph, categories, five branch statistics; workspace unchanged.')
}catch(error){await (await app.firstWindow()).screenshot({path:path.join(audit,'运行检查失败.png')});throw error}finally{await app.close()}
